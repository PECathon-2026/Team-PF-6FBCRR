"""Local Ollama AI Agent adapter."""
import json
import httpx
from typing import List
from app.config import settings
from app.models import SanitizedObservation, ActionProposal, ActionType
from .base import BaseAgent, SYSTEM_INSTRUCTION
from .mock_agent import MockAgent

class OllamaAgent(BaseAgent):
    def __init__(self, base_url: str = settings.ollama_base_url, model: str = settings.ollama_model):
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.fallback = MockAgent()

    async def propose_action(
        self,
        task: str,
        observation: SanitizedObservation,
        history: List[ActionProposal],
    ) -> ActionProposal:
        prompt = {
            "task": task,
            "page_origin": observation.page_origin,
            "page_title": observation.page_title,
            "elements": [
                {
                    "id": el.id,
                    "role": el.role,
                    "label": el.label,
                    "text": el.sanitized_text,
                    "is_interactive": el.is_interactive,
                }
                for el in observation.elements if el.is_interactive or el.label
            ],
            "history": [
                {"action": h.action_type.value, "element": h.element_id, "reason": h.reason}
                for h in history[-5:]
            ]
        }

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(
                    f"{self.base_url}/api/generate",
                    json={
                        "model": self.model,
                        "system": SYSTEM_INSTRUCTION,
                        "prompt": json.dumps(prompt),
                        "format": "json",
                        "stream": False,
                    }
                )
                if res.status_code == 200:
                    data = res.json()
                    response_text = data.get("response", "{}")
                    parsed = json.loads(response_text)
                    return ActionProposal(
                        action_type=ActionType(parsed.get("action_type", "finish")),
                        element_id=parsed.get("element_id"),
                        value=parsed.get("value"),
                        secret_alias=parsed.get("secret_alias"),
                        target_url=parsed.get("target_url"),
                        reason=parsed.get("reason", "Action generated by local Ollama model")
                    )
        except Exception:
            pass

        # Fallback to deterministic agent if Ollama is offline or uninstalled
        return await self.fallback.propose_action(task, observation, history)
