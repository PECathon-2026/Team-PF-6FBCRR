"""Screenshot masking and visual privacy sanitization module."""
import hashlib
import io
import time
from typing import List, Tuple, Optional
from PIL import Image, ImageDraw
from app.models import BoundingBox, SensitiveSpan, SensitiveCategory

# Map categories to distinct solid mask colors (opaque, RGB)
CATEGORY_COLORS = {
    SensitiveCategory.PASSWORD: (15, 23, 42),       # Dark slate
    SensitiveCategory.CREDIT_CARD: (185, 28, 28),   # Dark red
    SensitiveCategory.CVV: (220, 38, 38),           # Red
    SensitiveCategory.API_KEY: (126, 34, 206),      # Purple
    SensitiveCategory.JWT: (147, 51, 234),          # Light purple
    SensitiveCategory.AADHAAR: (194, 65, 12),       # Amber / orange
    SensitiveCategory.PAN: (180, 83, 9),            # Brown / gold
    SensitiveCategory.OTP: (190, 24, 93),           # Pink / magenta
    SensitiveCategory.EMAIL: (3, 105, 161),         # Blue
    SensitiveCategory.PHONE: (14, 116, 144),        # Cyan
    SensitiveCategory.FACE: (24, 24, 27),           # Black
    SensitiveCategory.SENSITIVE_REGION: (39, 39, 42),# Dark gray
}
DEFAULT_MASK_COLOR = (17, 24, 39)  # Solid dark gray

class ScreenshotSanitizer:
    def __init__(self, padding: int = 5):
        self.padding = padding
        # In-memory registry of approved sanitized image hashes
        self._approved_provenance_hashes: set[str] = set()

    def sanitize_screenshot(
        self,
        image_bytes: bytes,
        spans: List[SensitiveSpan],
        device_scale_factor: float = 1.0,
    ) -> Tuple[bytes, str, int]:
        """
        Applies irreversible solid opaque rectangles over all detected sensitive bounding boxes.
        Returns:
            - sanitized_png_bytes: Freshly encoded PNG without metadata
            - provenance_hash: SHA256 signature recorded in trusted local memory
            - masks_applied_count: Number of solid boxes drawn
        """
        if not image_bytes:
            raise ValueError("Empty image bytes provided to screenshot sanitizer")

        # Open image locally in memory
        with Image.open(io.BytesIO(image_bytes)) as img:
            # Convert to RGB to strip alpha/transparency and drop any EXIF/metadata
            rgb_img = img.convert("RGB")
            draw = ImageDraw.Draw(rgb_img)
            width, height = rgb_img.size

            masks_applied = 0

            for span in spans:
                if not span.bbox:
                    continue

                bbox = span.bbox
                # Scale coordinates if browser device scale factor != 1.0
                x1 = (bbox.x * device_scale_factor) - self.padding
                y1 = (bbox.y * device_scale_factor) - self.padding
                x2 = ((bbox.x + bbox.width) * device_scale_factor) + self.padding
                y2 = ((bbox.y + bbox.height) * device_scale_factor) + self.padding

                # Clamp to image boundaries
                x1 = max(0, min(x1, width - 1))
                y1 = max(0, min(y1, height - 1))
                x2 = max(0, min(x2, width))
                y2 = max(0, min(y2, height))

                if x2 <= x1 or y2 <= y1:
                    continue

                # Choose opaque color based on category
                color = CATEGORY_COLORS.get(span.category, DEFAULT_MASK_COLOR)

                # Draw IRREVERSIBLE solid opaque rectangle
                draw.rectangle([x1, y1, x2, y2], fill=color, outline=None)
                masks_applied += 1

            # Save as fresh PNG without metadata / EXIF
            output_buffer = io.BytesIO()
            rgb_img.save(output_buffer, format="PNG", optimize=True)
            sanitized_bytes = output_buffer.getvalue()

        # Compute cryptographic provenance hash
        hasher = hashlib.sha256()
        hasher.update(sanitized_bytes)
        hasher.update(f":{time.time()}:sanitized".encode("utf-8"))
        prov_hash = hasher.hexdigest()

        # Record in memory allowlist
        self._approved_provenance_hashes.add(prov_hash)

        return sanitized_bytes, prov_hash, masks_applied

    def verify_provenance(self, prov_hash: str) -> bool:
        """Verifies if the image hash was generated by this sanitizer."""
        return prov_hash in self._approved_provenance_hashes

    def revoke_provenance(self, prov_hash: str):
        self._approved_provenance_hashes.discard(prov_hash)
